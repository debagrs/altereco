async function aeLoadForumData() {
    if (!window.alterecoSupabase) {
        alterecoCommunityState.forumTopics = [];
        alterecoCommunityState.forumReplies = [];
        return;
    }
    try {
        const [topicsResult, repliesResult] = await Promise.all([
            window.alterecoSupabase.from('forum_topics').select('id,author_name,title,body,category,status,created_at,updated_at').eq('status', 'approved').order('created_at', { ascending: false }),
            window.alterecoSupabase.from('forum_replies').select('id,topic_id,author_name,body,status,created_at,updated_at').eq('status', 'approved').order('created_at', { ascending: true })
        ]);
        if (topicsResult.error) throw topicsResult.error;
        if (repliesResult.error) throw repliesResult.error;
        alterecoCommunityState.forumTopics = topicsResult.data || [];
        alterecoCommunityState.forumReplies = repliesResult.data || [];
    } catch (error) {
        console.error('Erro ao carregar fórum:', error);
        alterecoCommunityState.forumTopics = [];
        alterecoCommunityState.forumReplies = [];
    }
}

function aeReplyCount(topicId) {
    return alterecoCommunityState.forumReplies.filter(reply => reply.topic_id === topicId).length;
}

function aeForumDate(value) {
    const date = new Date(value);
    if (Number.isNaN(date.getTime())) return '';
    return new Intl.DateTimeFormat('pt-BR', { day: '2-digit', month: 'short', year: 'numeric' }).format(date);
}

function aeForumFilteredTopics() {
    const query = alterecoCommunityState.forumSearch.trim().toLocaleLowerCase('pt-BR');
    let items = [...alterecoCommunityState.forumTopics];
    if (query) items = items.filter(topic => `${topic.title} ${topic.body} ${topic.author_name} ${topic.category || ''}`.toLocaleLowerCase('pt-BR').includes(query));
    if (alterecoCommunityState.forumSort === 'comentados') {
        items.sort((a, b) => aeReplyCount(b.id) - aeReplyCount(a.id) || new Date(b.created_at) - new Date(a.created_at));
    } else {
        items.sort((a, b) => new Date(b.created_at) - new Date(a.created_at));
    }
    return items;
}

