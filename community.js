window.aeSubmitEvent = async function(event) {
    event.preventDefault();
    const form = event.currentTarget;
    const button = event.submitter;
    const feedback = document.getElementById('ae-event-feedback');
    const sourceUrl = form.source_url.value.trim();

    if (form.website.value) return;
    if (!/^https?:\/\//i.test(sourceUrl)) {
        feedback.textContent = 'Informe um link público para a página oficial ou fonte do evento.';
        feedback.className = 'ae-form-feedback is-error';
        return;
    }

    const payload = {
        title: form.title.value.trim(),
        organizer: form.organizer.value.trim(),
        description: form.description.value.trim(),
        event_kind: form.event_kind.value,
        start_date: form.start_date.value,
        end_date: form.end_date.value || form.start_date.value,
        format: form.format.value,
        location: form.location.value.trim() || null,
        city: form.city.value.trim() || null,
        country: form.country.value.trim() || null,
        source_url: sourceUrl,
        status: 'pending',
        submitted_by: await aeCurrentUserId(),
        submitter_name: form.submitter_name.value.trim() || null,
        featured: false
    };

    button.disabled = true;
    button.textContent = 'Enviando…';
    feedback.textContent = '';

    try {
        if (!window.alterecoSupabase) throw new Error('A conexão com o banco ainda não está disponível.');
        const { error } = await window.alterecoSupabase.from('events').insert(payload);
        if (error) throw error;
        form.reset();
        feedback.textContent = 'Evento enviado para a curadoria. Ele só aparecerá na agenda depois da aprovação da administração.';
        feedback.className = 'ae-form-feedback is-success';
    } catch (error) {
        console.error(error);
        feedback.textContent = /events|schema cache|relation|table/i.test(error.message || '')
            ? 'O formulário já está pronto, mas a nova migration do Supabase ainda precisa ser aplicada no deploy.'
            : `Não foi possível enviar agora: ${error.message}`;
        feedback.className = 'ae-form-feedback is-error';
    } finally {
        button.disabled = false;
        button.textContent = 'Enviar para curadoria';
    }
};

