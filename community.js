function aeDateFromISO(value) {
    const [year, month, day] = String(value || '').slice(0, 10).split('-').map(Number);
    if (!year || !month || !day) return null;
    return new Date(year, month - 1, day, 12, 0, 0);
}

function aeISODate(date) {
    return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`;
}

function aeFormatDate(value, options = {}) {
    const date = aeDateFromISO(value);
    if (!date) return '';
    return new Intl.DateTimeFormat('pt-BR', {
        day: '2-digit',
        month: options.short ? 'short' : 'long',
        year: 'numeric'
    }).format(date);
}

function aeEventDateLabel(event) {
    const start = aeFormatDate(event.start_date, { short: true });
    const end = event.end_date && event.end_date !== event.start_date
        ? aeFormatDate(event.end_date, { short: true })
        : '';
    return end ? `${start} — ${end}` : start;
}

function aeEventStatus(event) {
    const today = aeDateFromISO(new Date().toISOString().slice(0, 10));
    const start = aeDateFromISO(event.start_date);
    const end = aeDateFromISO(event.end_date || event.start_date);
    if (!start || !end) return '';
    if (today < start) return 'Próximo';
    if (today > end) return 'Encerrado';
    return 'Em andamento';
}

function aeKindLabel(kind) {
    const labels = {
        congresso: 'Congresso', conferencia: 'Conferência', simposio: 'Simpósio',
        encontro: 'Encontro', curso: 'Curso / formação', webinar: 'Webinar',
        workshop: 'Workshop', prazo: 'Prazo', outro: 'Outro'
    };
    return labels[kind] || 'Evento';
}

function aeFormatLabel(format) {
    return ({ presencial: 'Presencial', online: 'Online', hibrido: 'Híbrido' })[format] || format || '';
}

function aeEscape(value = '') {
    if (typeof window.escapeHtml === 'function') return window.escapeHtml(value);
    return String(value).replace(/[&<>"']/g, char => ({
        '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#039;'
    })[char]);
}

async function aeLoadApprovedEvents() {
    if (!window.alterecoSupabase) {
        alterecoCommunityState.events = [...window.ALTERECO_EVENT_SEED];
        return alterecoCommunityState.events;
    }

    try {
        const { data, error } = await window.alterecoSupabase
            .from('events')
            .select('id,title,organizer,description,event_kind,start_date,end_date,format,location,city,country,source_url,registration_url,tags,status,verified_at,featured,created_at,updated_at')
            .eq('status', 'approved')
            .order('start_date', { ascending: true });
        if (error) throw error;
        alterecoCommunityState.events = data?.length ? data : [...window.ALTERECO_EVENT_SEED];
    } catch (error) {
        console.warn('Agenda AlterECO usando base local até a migration ser aplicada:', error.message);
        alterecoCommunityState.events = [...window.ALTERECO_EVENT_SEED];
    }
    return alterecoCommunityState.events;
}

function aeEventsForMonth(year, month) {
    const first = new Date(year, month, 1, 12);
    const last = new Date(year, month + 1, 0, 12);
    return alterecoCommunityState.events.filter(event => {
        if (alterecoCommunityState.eventKind !== 'todos' && event.event_kind !== alterecoCommunityState.eventKind) return false;
        const start = aeDateFromISO(event.start_date);
        const end = aeDateFromISO(event.end_date || event.start_date);
        return start && end && start <= last && end >= first;
    });
}

function aeEventsForDay(date) {
    const stamp = aeISODate(date);
    return alterecoCommunityState.events.filter(event => {
        if (alterecoCommunityState.eventKind !== 'todos' && event.event_kind !== alterecoCommunityState.eventKind) return false;
        return event.start_date <= stamp && (event.end_date || event.start_date) >= stamp;
    });
}

function aeRenderCalendar() {
    const grid = document.getElementById('ae-calendar-days');
    const label = document.getElementById('ae-calendar-label');
    const list = document.getElementById('ae-event-list');
    if (!grid || !label || !list) return;

    const cursor = alterecoCommunityState.eventCursor;
    const year = cursor.getFullYear();
    const month = cursor.getMonth();
    const rawMonthLabel = new Intl.DateTimeFormat('pt-BR', { month: 'long', year: 'numeric' }).format(cursor);
    label.textContent = rawMonthLabel.charAt(0).toUpperCase() + rawMonthLabel.slice(1);

    const firstWeekday = new Date(year, month, 1).getDay();
    const daysInMonth = new Date(year, month + 1, 0).getDate();
    const todayISO = new Date().toISOString().slice(0, 10);
    let html = '';

    for (let blank = 0; blank < firstWeekday; blank++) {
        html += '<div class="ae-calendar-cell ae-calendar-cell--blank" aria-hidden="true"></div>';
    }

    for (let day = 1; day <= daysInMonth; day++) {
        const date = new Date(year, month, day, 12);
        const iso = aeISODate(date);
        const events = aeEventsForDay(date);
        const titles = events.map(event => event.title).join(' • ');
        html += `
            <button type="button" class="ae-calendar-cell ${iso === todayISO ? 'is-today' : ''} ${events.length ? 'has-event' : ''}"
                onclick="aeFocusDate('${iso}')" aria-label="${day} de ${label.textContent}${events.length ? `: ${aeEscape(titles)}` : ''}">
                <span class="ae-calendar-day">${day}</span>
                <span class="ae-calendar-marks" aria-hidden="true">
                    ${events.slice(0, 3).map(event => `<i class="ae-event-dot ae-event-dot--${aeEscape(event.event_kind)}"></i>`).join('')}
                    ${events.length > 3 ? `<small>+${events.length - 3}</small>` : ''}
                </span>
            </button>`;
    }
    grid.innerHTML = html;

    const monthEvents = aeEventsForMonth(year, month).sort((a, b) => a.start_date.localeCompare(b.start_date));
    list.innerHTML = monthEvents.length
        ? monthEvents.map(aeEventCardHTML).join('')
        : `<div class="ae-empty-state"><i data-lucide="calendar-x"></i><h3>Nenhum evento neste mês</h3><p>Você pode sugerir um evento para a curadoria AlterECO.</p></div>`;

    if (window.lucide) window.lucide.createIcons();
}

